  using      ((select has_perm('listings.edit')) or (select has_perm('listings.marketing'))
              or (select has_perm('checklists.manage')) or (select has_perm('roles.manage')))
  with check ((select has_perm('listings.edit')) or (select has_perm('listings.marketing'))
              or (select has_perm('checklists.manage')) or (select has_perm('roles.manage')));
create policy p_delete on public.listing_checklist_item for delete to authenticated
  using ((select has_perm('listings.edit')) or (select has_perm('listings.marketing'))
         or (select has_perm('checklists.manage')) or (select has_perm('roles.manage')));;
